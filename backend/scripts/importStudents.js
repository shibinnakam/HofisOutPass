  const line = lines[i].trim();
  if (!line) continue;
  
  // Format: SNo,Name,Admission Number,Class,Father Name
  const parts = line.split(',');
  if (parts.length < 5) continue;

  const sno = parts[0].trim();
  const name = parts[1].trim();
  const adm = parts[2].trim();
  const classFull = parts[3].trim();
  // Father name could have commas if any, join remaining
  const fatherName = parts.slice(4).join(',').trim();

  // Split Class and Division:
  // e.g. "V A" -> class: "V", division: "A"
  // e.g. "PRE KG A" -> class: "PRE KG", division: "A"
  // e.g. "VI B" -> class: "VI", division: "B"
  let cls = classFull;
  let div = "";
  const lastSpaceIdx = classFull.lastIndexOf(' ');
  if (lastSpaceIdx !== -1) {
    cls = classFull.substring(0, lastSpaceIdx).trim();
    div = classFull.substring(lastSpaceIdx + 1).trim();
  }

  students.push({
    admissionNumber: adm,
    studentName: name,
    fatherName: fatherName,
    class: cls,
    division: div,
    contactNumber: "+91 98765 43210"
  });
